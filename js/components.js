/**
 * Toast Notification Helper - Clean, understated notification
 */
export function showToast(message, type = 'success') {
    let container = document.getElementById('toast-container');
    if (!container) {
        container = document.createElement('div');
        container.id = 'toast-container';
        container.className = 'toast-container';
        document.body.appendChild(container);
    }
    const toast = document.createElement('div');
    toast.className = `toast ${type}`;
    toast.innerHTML = `
        <span class="toast-icon">${type === 'success' ? Icons.check : '•'}</span>
        <div class="toast-message">${message}</div>
    `;
    container.appendChild(toast);
    setTimeout(() => {
        toast.style.opacity = '0';
        toast.style.transform = 'translateY(8px)';
        toast.style.transition = 'all 0.2s ease';
        setTimeout(() => toast.remove(), 200);
    }, 2800);
}

/**
 * Clean Modal Dialog
 */
export function openModal(title, bodyHTML, onSaveCallback) {
    let overlay = document.getElementById('app-modal');
    if (!overlay) {
        overlay = document.createElement('div');
        overlay.id = 'app-modal';
        overlay.className = 'modal-overlay';
        overlay.innerHTML = `
            <div class="modal-content">
                <div class="modal-header">
                    <h3 class="modal-title" id="modal-title">Form</h3>
                    <button class="icon-btn-close" id="modal-close-btn">&times;</button>
                </div>
                <div class="modal-body" id="modal-body"></div>
                <div class="modal-footer">
                    <button class="btn-secondary" id="modal-cancel-btn">Cancel</button>
                    <button class="btn-primary" id="modal-save-btn">Save Changes</button>
                </div>
            </div>
        `;
        document.body.appendChild(overlay);

        document.getElementById('modal-close-btn').onclick = closeModal;
        document.getElementById('modal-cancel-btn').onclick = closeModal;
        overlay.onclick = (e) => { if (e.target === overlay) closeModal(); };
    }

    document.getElementById('modal-title').textContent = title;
    document.getElementById('modal-body').innerHTML = bodyHTML;
    overlay.classList.add('active');

    const saveBtn = document.getElementById('modal-save-btn');
    saveBtn.onclick = () => {
        if (onSaveCallback) {
            const success = onSaveCallback();
            if (success !== false) closeModal();
        }
    };
}

export function closeModal() {
    const overlay = document.getElementById('app-modal');
    if (overlay) overlay.classList.remove('active');
}

/**
 * Format Currency Helper
 */
export function formatCurrency(amount) {
    return '$' + Number(amount || 0).toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 });
}

/**
 * Status Badge Renderer - Simple, understated status pill
 */
export function renderStatusBadge(status) {
    const s = String(status || 'Operational').toLowerCase().replace(/\s+/g, '-');
    return `<span class="badge badge-${s}"><span class="badge-dot"></span>${status}</span>`;
}
